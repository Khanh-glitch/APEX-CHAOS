import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read=(name)=>readFileSync(new URL('../'+name,import.meta.url),'utf8');
const shader=read('public/game/evolution/apexEvolutionShaderCompositor.js');
const bridge=read('public/game/gold/goldProductBridge.js');
const arena=read('public/game/arsenal/apexBeyondArenaEngine.js');
const css=read('src/ui/freeBattleBeyondHud.css');
const hud=read('src/ui/FreeBattleBeyondHud.jsx');
const original=read('public/game/evolution/apexEvolutionArenas.js');
const ids=['scrap_foundry','cryo_vault','lorentz_railyard','prism_sanctum','tournament_pro'];
for(const id of ids) assert.ok(original.includes(id),'Arena absent: '+id);
assert.ok(bridge.includes('arena.appendChild(canvas)'),'Gold arena ownership changed');
assert.ok(shader.includes("glCanvas.id = 'apex-evolution-webgl-offscreen'"),'GPU compositor is not detached');
assert.ok(!shader.includes('parent.insertBefore(glCanvas'),'Potential duplicate arena overlay found');
assert.ok(!shader.includes('parent.appendChild(glCanvas'),'Potential duplicate arena overlay found');
assert.ok(shader.includes("scene2d.globalCompositeOperation = 'copy'"),'Missing single-canvas GPU handoff');
assert.ok(hud.includes('getBoundingClientRect()'),'HUD missing arena geometry');
assert.ok(css.includes('var(--ab-arena-center)'),'HUD not anchored to arena');
assert.ok(css.includes('var(--ab-arena-bottom)'),'HUD not anchored to arena bottom');
assert.ok(arena.includes('original.drawArenaFloor(ctx'),'Missing original donor floor');
assert.ok(arena.includes('original.stepArenaMechanics(d)'),'Missing donor hazard simulation');
console.log('ARENA INTEGRATION PASS: 5 donor stages; single scene; GPU offscreen; Gold geometry; panel-safe HUD; donor mechanics.');
