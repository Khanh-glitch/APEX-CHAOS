import { createRequire } from 'node:module';
import fs from 'node:fs';
const require = createRequire(new URL('../node_modules/', import.meta.url));
const puppeteer = require('puppeteer-core');
const chromium = require('@sparticuz/chromium');
const { startServer } = await import('../../perf/goldNestedServer.mjs');
const REPO = '/home/user/APEX-CHAOS';
const seed = fs.readFileSync(REPO + '/tools/perf/qaProfile.js', 'utf8');
const srv = await startServer({ root: REPO + '/dist-itch-html5' });
const browser = await puppeteer.launch({ executablePath: await chromium.executablePath(), headless: true, protocolTimeout: 600000, args: [...chromium.args, '--no-sandbox'] });
const page = await browser.newPage();
await page.setViewport({ width: 1440, height: 900, deviceScaleFactor: 1 });
await page.evaluateOnNewDocument(seed);
await page.goto(srv.nested, { waitUntil: 'domcontentloaded', timeout: 120000 });
await page.waitForSelector('#apex-boot-start', { timeout: 180000 });
await page.evaluate(() => document.getElementById('apex-boot-start').click());
await page.waitForSelector('#freeBattle', { visible: true, timeout: 180000 });
await page.evaluate(() => { document.body.classList.remove('apex-scene-transition-active'); document.body.dataset.apexSceneTransition='DONE'; const cv=document.getElementById('apex-scene-transition'); if(cv) cv.style.display='none'; });
await new Promise(r => setTimeout(r, 2500));
const out = await page.evaluate(() => {
  const a = window.APEX_GRAPHICS_ADVISOR;
  const p = () => { const el = document.getElementById('apex-quality-advisor'); return { hidden: el?.hidden, open: el ? !el.hidden : false }; };
  const log = [];
  window.APEX_GRAPHICS_QUALITY.set('high','dbg');
  a._test.reset();
  log.push({ step: 'after reset', windows: a._test.debug().windows.slice(), panel: p() });
  const slow = new Array(30).fill(45);
  const r1 = a._test.evaluate(slow);
  log.push({ step: 'eval1', recommend: r1.recommend, streak: r1.streak, windows: a._test.debug().windows.slice(), panel: p() });
  const r2 = a._test.evaluate(slow);
  log.push({ step: 'eval2', recommend: r2.recommend, streak: r2.streak, windows: a._test.debug().windows.slice(), panel: p() });
  const r3 = a._test.evaluate(slow);
  log.push({ step: 'eval3', recommend: r3.recommend, windows: a._test.debug().windows.slice(), panel: p() });
  return { log, verdict: { analysis: a._test.analyse(slow) } };
});
console.log(JSON.stringify(out, null, 1));
await browser.close(); await srv.server.close(); process.exit(0);
