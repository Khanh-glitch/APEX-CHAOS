import assert from 'node:assert/strict';
import {createWaveInputRouter,waveControlsFor,pickWaveAutoTarget,joystickVector} from '../src/game/botWave/inputRouter.js';
import {upgradeState} from '../src/game/botWave/upgradeRegistry.js';
const p=upgradeState(),events=[];
const input=createWaveInputRouter({getUpgradeState:()=>p,onAction:e=>events.push(e)});
assert.deepEqual(input.controls().filter(x=>x.enabled).map(x=>x.key),['J','K','L']);
assert.deepEqual(input.controls().filter(x=>!x.enabled).map(x=>x.key),['U','I']);
assert.equal(input.trigger('J').accepted,true);
assert.equal(input.trigger('K',{source:'touch'}).accepted,true);
assert.equal(input.trigger('L',{source:'touch'}).accepted,true);
assert.equal(input.trigger('U').accepted,false);
assert.equal(input.trigger('I',{source:'touch'}).accepted,false);
assert.equal(input.trigger('0').accepted,false);
assert.equal(events.length,3);
p.owned.add('unlock-jab-finisher');
p.owned.add('unlock-uppercut-finisher');
p.owned.add('unlock-counter');
assert.deepEqual(input.controls().filter(x=>x.enabled).map(x=>x.key),['J','K','L']);
assert.deepEqual(input.controls().find(x=>x.key==='K').goldEnabled,true);
p.owned.add('unlock-phantom');
assert.equal(input.trigger('U',{source:'touch'}).accepted,true);
assert.equal(input.trigger('I',{source:'keyboard'}).accepted,false);
p.owned.add('unlock-ultimate');
assert.equal(input.trigger('I',{source:'touch'}).accepted,true);
assert.equal(events.at(-1).goldKey,'0');
const player={x:10,y:10},enemies=[{id:'bot-B',x:20,y:15},{id:'bot-A',x:20,y:15},{id:'dead',x:11,y:10,alive:false}];
assert.equal(pickWaveAutoTarget(player,enemies),'bot-A');
assert.equal(pickWaveAutoTarget(player,[]),null);
assert.deepEqual(joystickVector(.01,.02),{x:0,y:0});
assert.deepEqual(joystickVector(3,4),{x:.6,y:.8});
console.log('BOT WAVE dual-input PASS: J/K/L only at start, K counter and J finishers via cards; touch U/I locked; auto target nearest; joystick normalized');
