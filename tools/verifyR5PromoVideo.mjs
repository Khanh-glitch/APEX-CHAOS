import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {spawnSync} from 'node:child_process';
const require=createRequire(import.meta.url);
const binary=require('@ffmpeg-installer/ffmpeg').path;
const root=path.resolve('reports/promo-offline-r5');
const mp4=path.join(root,'APEX-CHAOS-CRYSTALA-HEXA-60FPS-RAW.mp4');
const info=JSON.parse(fs.readFileSync(path.join(root,'receipt.json'),'utf8'));
assert.equal(info.frames,420);
assert.equal(info.fps,60);
assert(info.result?.prisonConstructed,'HEXA must have occurred in the real game');
assert(info.result?.casts.some(c=>c.side==='CRYSTAL'&&c.slot==='A2'&&c.ok),'K must succeed');
assert(info.result?.casts.some(c=>c.side==='CRYSTAL'&&c.slot==='A1'&&c.ok),'J must succeed');
assert.equal(fs.statSync(mp4).size>1e5,true,'MP4 is implausibly small');
const r=spawnSync(binary,['-hide_banner','-i',mp4,'-f','null','-'],{encoding:'utf8',maxBuffer:20e6,timeout:180000});
if(r.error)throw r.error;
const log=r.stderr||'';
assert.equal(r.status,0,'video decode failed: '+log.slice(-1400));
assert(/1080x1920/.test(log),'wrong output dimensions: '+log.slice(0,1000));
assert(/60 fps/.test(log),'wrong output cadence: '+log.slice(0,1000));
assert(/frame=\s*420\b/.test(log),'incorrect final frame count: '+log.slice(-1200));
console.log('PASS: real-game HEXA captured, MP4 decodes all 420 frames at 1080x1920/60fps; original R5 unchanged.');
